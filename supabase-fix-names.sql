--
-- เกิดกับบัญชีที่ตั้ง PIN ตั้งแต่ก่อนกรอกชื่อในทะเบียนพนักงาน
-- โปรไฟล์เลยเก็บเบอร์ไว้เป็นชื่อ สคริปต์นี้ดึงชื่อจากทะเบียนมาแทนให้
--
-- วิธีใช้: Supabase → SQL Editor → New query → วางทั้งไฟล์ → Run
-- ============================================================

-- 1) ดูก่อนว่ามีบัญชีไหนที่ชื่อยังเป็นเบอร์
select p.phone as "เบอร์", p.name as "ชื่อในโปรไฟล์", e.name as "ชื่อในทะเบียนพนักงาน"
  from public.profiles p
  left join public.employees e on e.phone = p.phone
 order by p.phone;

-- 2) เติมชื่อจากทะเบียนพนักงาน (เฉพาะบัญชีที่ชื่อยังว่างหรือเป็นเบอร์)
update public.profiles p
   set name = e.name
  from public.employees e
 where e.phone = p.phone
   and coalesce(nullif(btrim(e.name), ''), '') <> ''
   and coalesce(nullif(btrim(p.name), ''), p.phone) = p.phone;

-- 3) ตรวจผล
select p.phone as "เบอร์", p.name as "ชื่อ", p.role as "สิทธิ์"
  from public.profiles p
 order by p.name nulls last;

-- ============================================================
-- ถ้าคนไหนยังขึ้นเป็นเบอร์อยู่ แปลว่ายังไม่ได้กรอกชื่อในทะเบียนพนักงาน
-- ให้ไปกรอกที่เมนู "ข้อมูลพนักงาน" ในหน้าแอดมิน แล้วรันไฟล์นี้อีกครั้ง
